def evaluate_model(y_true, y_pred,model_name,y_score = None):
    
    acc = accuracy_score(y_true, y_pred)
    class_report = classification_report(y_true, y_pred)
    cm = confusion_matrix(y_true, y_pred)
    roc_auc = None
    pr_auc = None
    
    if y_score is not None:
        roc_auc = roc_auc_score(y_true, y_score,average='macro' )
        pr_auc = average_precision_score(y_true, y_score,average='macro')
    else:
        pass
          
    print(f"Test accuracy:       {acc:.4f}")
    if roc_auc is not None:
        print(f"ROC-AUC:             {roc_auc:.4f}")
    if pr_auc is not None:
        print(f"PR-AUC:              {pr_auc:.4f}")
    print(f"{'-'*65}")
    print("Classification Report:")
    print(class_report)
    print(f"{'-'*65}")
    print("Confusion Matrix:")
    print(cm)
    print(f"{'='*65}\n")
    return acc, roc_auc, pr_auc

def train_class_model(user_df):
    
    #datawrankling
    user_df["company"] = user_df["company"].astype(str).str.strip()
    user_df["name"] = user_df["name"].astype(str).str.strip()
    user_df["gender"] = user_df["gender"].astype(str).str.strip().str.lower()

    duplicates_before = user_df.duplicated().sum()
    user_df = user_df.drop_duplicates().copy()

    undefined_gender = user_df["gender"].eq("none").sum()
    user_df = user_df[user_df["gender"].isin(["male", "female"])].copy()

    user_df = user_df.dropna(subset=["company", "name", "gender", "age"])

    user_df = user_df.reset_index(drop=True)
    #feature engineering
    feature_df = user_df.copy()

    feature_df["name"] = feature_df["name"].str.lower().str.strip()

    feature_df["first_name"] = feature_df["name"].str.split().str[0]

    feature_df["first_name_length"] = (feature_df["first_name"].str.len())

    feature_df["last_letter"] = (feature_df["first_name"].str[-1])

    feature_df["vowel_count"] = (feature_df["first_name"].str.count(r"[aeiou]"))

    feature_df["vowel_ratio"] = (feature_df["vowel_count"]/ feature_df["first_name_length"].replace(0, np.nan)).fillna(0)

    feature_df["age"] = pd.to_numeric(feature_df["age"],errors="coerce")

    feature_df = feature_df.dropna(subset=["age", "first_name"]).reset_index(drop=True)

    x = feature_df.drop(columns=["gender", 'code', 'name'], axis=1)
    y = feature_df["gender"].map({"male": 0, "female": 1})
    

    # 2. Define features
    text_feature = 'first_name'
    categorical_features = ['last_letter', 'company']

    # 3. Build Pipeline
    preprocessor = ColumnTransformer(
    transformers=[
        ("tfidf",TfidfVectorizer(analyzer="char",
    ngram_range=(2, 4),
    lowercase=True,
    min_df=2,
    sublinear_tf=True),text_feature),
        ("categorical",OneHotEncoder(handle_unknown="ignore"),categorical_features)],
    remainder='drop' # Explicitly dropping untransformed columns (default behavior)
)

    full_pipeline = Pipeline([("preprocess", preprocessor), ("scale", RobustScaler(with_centering=False)) ])
    x=full_pipeline.fit_transform(x)
    new_column_names = full_pipeline.get_feature_names_out()
    x= pd.DataFrame(x.toarray(), columns=new_column_names)
    # 4. Fit and Transform (Returns Sparse Matrices)
    #x_train_scaled_sparse = full_pipeline.fit_transform(x_train)
    #x_test_scaled_sparse = full_pipeline.transform(x_test)

    # 5. Get the NEW column names generated by the pipeline
    #new_column_names = full_pipeline.get_feature_names_out()

    #x_train_scaled = pd.DataFrame(x_train_scaled_sparse.toarray(), columns=new_column_names)
    #x_test_scaled = pd.DataFrame(x_test_scaled_sparse.toarray(), columns=new_column_names)
    
    x_train, x_test, y_train, y_test = train_test_split(x, y, test_size=0.2, random_state=42)
    Linear_SVM = Pipeline([ ("Linear_SVM", LinearSVC(random_state=42))])
    model=Linear_SVM.fit(x_train ,y_train)
    y_pred_svc_base = model.predict(x_test)
    #y_pred_lr_proba= model.predict_proba(x_test)[:, 1]

    evaluate_model(y_test, y_pred_svc_base,'Logistic Regression')
    
    return x_test,y_test,model,y_pred_svc_base,full_pipeline
def mlflow_track():
    mlflow.set_tracking_uri(os.getenv("MLFLOW_TRACKING_URI"))
    mlflow.set_experiment("Gender_Classification")
    #mlflow.autolog() # Autolog will now work without serialization errors
    x_test,y_test,model,y_pred_svc_base,full_pipeline = train_class_model(user_df)
    with mlflow.start_run(run_name="Linear SVM_gender_classification"):
        acc, roc_auc, pr_auc = evaluate_model(y_test, y_pred_svc_base,'Linear SVM')
        mlflow.log_params(model.get_params())
        mlflow.log_metric("accuracy", acc)
        if roc_auc is not None:
            mlflow.log_metric("roc_auc", roc_auc)    
        if pr_auc is not None:
            mlflow.log_metric("pr_auc", pr_auc)  
        mlflow.set_tag('Training Info', 'Linear SVM model for Gender Classification')
        signature1 = mlflow.models.infer_signature(x_test, model.predict(x_test))
        mlflow.sklearn.log_model(
            model,  
            name="Linear_SVM_gender_classification", 
            signature=signature1,
            input_example=x_test.head(5),
            registered_model_name="Linear_SVM_gender_classification" 
        )
        mlflow.sklearn.log_model(
        full_pipeline,
        name="gender_classification_preprocess_pipeline",
        serialization_format="cloudpickle",
        registered_model_name="gender_classification_preprocess_pipeline"
    )
        print("Model and pipeline successfully logged to MLflow!")
